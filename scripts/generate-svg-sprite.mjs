#!/usr/bin/env node
/**
 * SVG Sprite Generator
 * Reads SVGs from public/svg/ subdirectories and generates:
 *  - public/svg/sprite.svg        (the sprite sheet)
 *  - src/app/svg-sprite-meta.ts   (TS metadata map with dimensions)
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, '..');

const outputSprite = path.join(root, 'public', 'svg', 'sprite.svg');
const outputMeta = path.join(root, 'src', 'app', 'svg-sprite-meta.ts');

// Directories to scan (relative to public/svg). Each SVG gets id "<prefix>-<filename_without_ext>"
const INCLUDE_DIRS = [
  { dir: 'about',     prefix: 'about' },
  { dir: 'contact',   prefix: 'contact' },
  { dir: 'logos',     prefix: 'logos' },
  { dir: 'not-found', prefix: 'not-found' },
];

// Single files at the root of public/svg
const INCLUDE_FILES = [
  { file: 'Name.svg', id: 'name' },
];

// ─── helpers ──────────────────────────────────────────────────────────────────

function extractAttr(content, attr) {
  // Match the attribute; skip "data-name" etc. by requiring word boundary before attr
  const re = new RegExp(`(?:^|\\s)${attr}="([^"]*)"`, 'm');
  const m = content.match(re);
  return m ? m[1] : null;
}

function stripSvgWrapper(content) {
  return content
    .replace(/<\?xml[^>]*\?>\s*/g, '')        // remove XML prolog
    .replace(/<!--[\s\S]*?-->/g, '')           // remove comments
    .replace(/<svg[^>]*>/g, '')               // remove opening <svg ...>
    .replace(/<\/svg>\s*$/, '')               // remove closing </svg>
    .replace(/\s+id="[^"]*"/g, '')            // strip all internal id attributes
    .replace(/\s+data-name="[^"]*"/g, '')     // strip data-name attributes (Illustrator artefacts)
    .trim();
}

// ─── main ─────────────────────────────────────────────────────────────────────

const symbols = [];
const meta = {};

function processFile(filePath, id) {
  if (!fs.existsSync(filePath)) {
    console.warn(`  ⚠ File not found: ${filePath}`);
    return;
  }
  const content = fs.readFileSync(filePath, 'utf-8');

  const viewBox = extractAttr(content, 'viewBox') ?? '0 0 100 100';
  const width   = extractAttr(content, 'width');
  const height  = extractAttr(content, 'height');
  const inner   = stripSvgWrapper(content);

  symbols.push(`  <symbol id="${id}" viewBox="${viewBox}">\n${inner}\n  </symbol>`);
  meta[id] = { viewBox, width, height };
}

// Process directory entries
for (const { dir, prefix } of INCLUDE_DIRS) {
  const dirPath = path.join(root, 'public', 'svg', dir);
  if (!fs.existsSync(dirPath)) { console.warn(`  ⚠ Directory not found: ${dirPath}`); continue; }

  const files = fs.readdirSync(dirPath)
    .filter(f => f.endsWith('.svg'))
    .sort();

  for (const file of files) {
    const id = `${prefix}-${path.basename(file, '.svg')}`;
    processFile(path.join(dirPath, file), id);
  }
}

// Process individual root files
for (const { file, id } of INCLUDE_FILES) {
  processFile(path.join(root, 'public', 'svg', file), id);
}

// ─── Write sprite ─────────────────────────────────────────────────────────────
const spriteContent = [
  `<?xml version="1.0" encoding="UTF-8"?>`,
  `<svg xmlns="http://www.w3.org/2000/svg" style="display:none" aria-hidden="true">`,
  ...symbols,
  `</svg>`,
].join('\n');

fs.writeFileSync(outputSprite, spriteContent, 'utf-8');

// ─── Write TypeScript metadata ────────────────────────────────────────────────
const metaContent = `// AUTO-GENERATED by scripts/generate-svg-sprite.mjs – DO NOT EDIT MANUALLY
// Re-run: node scripts/generate-svg-sprite.mjs  (or via npm run build / npm start)

export interface SvgSymbolMeta {
  viewBox: string;
  /** Original SVG width attribute (e.g. "35.28mm"). null if not present. */
  width: string | null;
  /** Original SVG height attribute (e.g. "52.92mm"). null if not present. */
  height: string | null;
}

export const SVG_SPRITE_META: Record<string, SvgSymbolMeta> = ${JSON.stringify(meta, null, 2)};
`;

fs.writeFileSync(outputMeta, metaContent, 'utf-8');

console.log(`✓ SVG sprite generated with ${symbols.length} symbols`);
console.log(`  → ${outputSprite}`);
console.log(`  → ${outputMeta}`);

